#!/usr/bin/env python3
"""Generate release.yml with complete artifact handoffs before publication.

Run cargo-dist against a copy of the tracked working files so its stock CI
renderer can run with the overlay opt-out removed. The real config opts out
of dist's byte-for-byte check. This generator checks the rendered result,
including the overlay, in ordinary CI and before a release build.
"""

import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
WORKFLOW = Path(".github/workflows/release.yml")
CONFIG = Path("dist-workspace.toml")
OPT_OUT = 'allow-dirty = ["ci"]\n'


def replace_once(source, old, new):
    """Refuse template drift before an upstream change can bypass a check."""
    if source.count(old) != 1:
        raise ValueError(f"expected one copy of {old!r} in the generator input")
    return source.replace(old, new)


def render_dist(dist):
    """Render stock dist CI without rewriting any files in the checkout."""
    staging = ROOT / "target"
    staging.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="release-workflow-", dir=staging) as directory:
        tree = Path(directory)
        paths = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT)
        for item in paths.split(b"\0"):
            if not item:
                continue
            path = Path(os.fsdecode(item))
            source = ROOT / path
            if not (source.is_file() or source.is_symlink()):
                continue
            destination = tree / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination, follow_symlinks=False)
        config = tree / CONFIG
        config.write_text(replace_once(config.read_text(), OPT_OUT, ""))
        subprocess.run(["git", "init", "-q"], cwd=tree, check=True)
        origin = subprocess.check_output(["git", "remote", "get-url", "origin"], cwd=ROOT, text=True).strip()
        subprocess.run(["git", "remote", "add", "origin", origin], cwd=tree, check=True)
        subprocess.run([dist, "generate", "--mode", "ci"], cwd=tree, check=True)
        return (tree / WORKFLOW).read_text()


def archive_names():
    """Share the validator's archive list, which the Rust parity test checks."""
    source = (ROOT / ".github/workflows/sign-sums.yml").read_text()
    archives = re.search(r"(?m)^  SUMS_MEMBERS: \|\n((?:    [\w.-]+\.tar\.gz\n)+)", source)
    if archives is None:
        raise ValueError("could not read release archive list from sign-sums.yml")
    return archives[1].split()


def protect_download(source, comment, name, gate, phase):
    """Retry an incomplete listing once with the same artifact digest checks."""
    download = re.search(
        rf'{re.escape(comment)}\n'
        rf'      - name: {re.escape(name)}\n'
        r'        uses: actions/download-artifact@[^\n]+\n'
        r'        with:\n'
        r'          pattern: artifacts-\*\n'
        r'          path: target/distrib/\n'
        r'          merge-multiple: true\n',
        source,
    )
    if download is None:
        raise ValueError(f"cargo-dist no longer emits the expected {name!r} step")
    first_check = gate.replace(
        "        env:\n", "        id: artifact-handoff\n        continue-on-error: true\n        env:\n", 1
    )
    retry_condition = "        if: steps.artifact-handoff.outcome == 'failure'\n"
    retry = download[0].split("\n", 1)[1].replace(
        f"      - name: {name}\n", f"      - name: Retry artifact download\n{retry_condition}"
    )
    final_check = gate.replace("        env:\n", retry_condition + "        env:\n", 1)
    return replace_once(
        source, download[0], f"{download[0]}{first_check} {phase}\n{retry}{final_check} {phase}\n"
    )


def overlay(source, archive_names):
    """Use the local manifest and fail closed on any incomplete upload set."""
    source = replace_once(
        source,
        "# This file was autogenerated by dist:",
        "# Regenerate with: python3 releasing/generate-workflow.py\n"
        "# This file was autogenerated by dist:",
    )
    plan_command = '          dist ${{ (!github.event.pull_request'
    source = replace_once(
        source, plan_command, "          python3 releasing/generate-workflow.py --check\n" + plan_command
    )
    # Platform builds need the plan. Sibling uploads can appear at any point
    # during the matrix and must not become build inputs for other platforms.
    plan_download = re.search(
        r'      # Get the dist-manifest\n'
        r'      - name: Fetch local artifacts\n'
        r'        uses: actions/download-artifact@[^\n]+\n'
        r'        with:\n'
        r'          pattern: artifacts-\*\n'
        r'          path: target/distrib/\n'
        r'          merge-multiple: true\n',
        source,
    )
    if plan_download is None:
        raise ValueError("cargo-dist no longer emits the expected platform plan download")
    source = replace_once(
        source,
        plan_download[0],
        plan_download[0].replace("Fetch local artifacts", "Fetch the release plan")
        .replace("pattern: artifacts-*", "name: artifacts-plan-dist-manifest")
        .replace("          merge-multiple: true\n", ""),
    )
    artifacts = "\n".join(f"            {filename}" for filename in archive_names)
    gate = (
        "      - name: Check artifact handoff\n"
        "        env:\n"
        "          RELEASE_ARCHIVES: |\n"
        f"{artifacts}\n"
        "        run: bash releasing/check-artifact-handoff.sh target/distrib"
    )
    # An omitted platform must fail before dist can compute checksums or merge its manifests.
    source = protect_download(
        source,
        "      # Get all the local artifacts for the global tasks to use (for e.g. checksums)",
        "Fetch local artifacts",
        gate,
        "local",
    )
    source = protect_download(source, "      # Fetch artifacts from scratch-storage", "Fetch artifacts", gate, "global")
    download = re.search(
        r'      # Create a GitHub Release while uploading all files to it\n'
        r'      - name: "Download GitHub Artifacts"\n'
        r'        uses: actions/download-artifact@[^\n]+\n'
        r'        with:\n'
        r'          pattern: artifacts-\*\n'
        r'          path: artifacts\n'
        r'          merge-multiple: true\n'
        r'      - name: Cleanup\n'
        r'        run: \|\n'
        r'          # Remove the granular manifests\n'
        r'          rm -f artifacts/\*-dist-manifest\.json\n',
        source,
    )
    if download is None:
        raise ValueError("cargo-dist no longer emits the expected GitHub release download")
    source = replace_once(
        source,
        download[0],
        "      - name: Stage the complete release\n"
        "        env:\n"
        "          RELEASE_ARCHIVES: |\n"
        f"{artifacts}\n"
        "        run: bash releasing/check-artifact-handoff.sh target/distrib publish\n",
    )
    source = replace_once(source, ' --notes-file "$RUNNER_TEMP/notes.txt" artifacts/*',
                          ' --notes-file "$RUNNER_TEMP/notes.txt" --verify-tag release-assets/*')
    return source


def test_handoffs():
    """Exercise the inputs that can be absent from a successful artifact listing."""
    with tempfile.TemporaryDirectory(prefix="release-handoff-", dir=ROOT / "target") as directory:
        tree = Path(directory)
        distrib = tree / "distrib"
        distrib.mkdir()
        (distrib / "plan-dist-manifest.json").write_text("fixture\n")
        archives = archive_names()
        for archive in archives:
            target = archive.removesuffix(".tar.gz").removeprefix("farhelm-").removeprefix("desktop-")
            for name in (archive, f"{archive}.sha256", f"{target}-dist-manifest.json"):
                (distrib / name).write_text("fixture\n")

        def run(phase):
            return subprocess.run(
                ["bash", ROOT / "releasing/check-artifact-handoff.sh", distrib, phase],
                cwd=tree,
                env={**os.environ, "RELEASE_ARCHIVES": "\n".join(archives)},
                capture_output=True,
                text=True,
                check=False,
            )

        assert run("local").returncode == 0
        missing = distrib / archives[-1]
        missing.unlink()
        result = run("local")
        assert result.returncode and missing.name in result.stderr, result
        missing.write_text("fixture\n")
        (distrib / "global-dist-manifest.json").write_text("fixture\n")
        result = run("global")
        assert result.returncode and "sha256.sum" in result.stderr, result
        (distrib / "sha256.sum").write_text("fixture\n")
        assert run("global").returncode == 0
        result = run("publish")
        assert result.returncode and "dist-manifest.json" in result.stderr, result
        assert not (tree / "release-assets").exists()
        (tree / "dist-manifest.json").write_text("authoritative manifest\n")
        (distrib / "dist-manifest.json").write_text("stale manifest\n")
        result = run("publish")
        assert result.returncode == 0, result
        staged = tree / "release-assets"
        assert (staged / "dist-manifest.json").read_text() == "authoritative manifest\n"
        shutil.rmtree(staged)
        (distrib / "unexpected.tar.gz").write_text("fixture\n")
        result = run("publish")
        assert result.returncode and "+unexpected.tar.gz" in result.stdout, result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--self-test", action="store_true")
    parser.add_argument("--dist", default="dist", help="path to the pinned cargo-dist binary")
    args = parser.parse_args()

    if args.self_test:
        (ROOT / "target").mkdir(exist_ok=True)
        test_handoffs()
        print("release artifact handoff self-test passed")
        return
    dist = shutil.which(args.dist)
    if dist is None:
        parser.exit(1, f"could not find cargo-dist at {args.dist!r}\n")
    generated = overlay(render_dist(str(Path(dist).absolute())), archive_names())
    output = ROOT / WORKFLOW
    if args.check:
        if output.read_text() != generated:
            parser.exit(1, f"{WORKFLOW} is stale. Run python3 releasing/generate-workflow.py.\n")
    else:
        output.write_text(generated)


if __name__ == "__main__":
    main()

//! Viewer input for terminals in terminal hosts: the bytes a program reads
//! for each grid input message.
//!
//! For a tmux terminal the browser's xterm.js encodes keys, mouse reports,
//! focus reports and pastes itself, from the program's modes as it tracks
//! them, and the supervisor passes the bytes through. For a terminal in a
//! terminal host the grid client only reports what the user did
//! ([`GridInput`]: `key`, `text`, `paste`, `mouse`, `focus`), and the
//! program's modes live in the supervisor's emulator, so this module turns
//! each message into bytes from those modes. It is pure: no I/O, no clock,
//! and the only state is the paste in progress, so the grid sender that
//! receives messages and writes `Input` frames to the host owns everything
//! else.
//!
//! The target is byte-for-byte what today's terminal sends, because agents
//! and shells depend on it (SPEC.md promises Shift+Enter's and Escape's
//! behavior), and today's terminal is xterm.js 6.0.0 as vendored in
//! `crates/farhelm-ui/assets/vendor/xterm.js`, with Farhelm's options and
//! its own additions in `terminal.js`:
//!
//! - **Keys** ([`encode_key`]): for a keydown xterm.js would send a
//!   sequence for, the sequence its `evaluateKeyboardEvent` computes, legacy
//!   xterm encoding only (the kitty keyboard protocol stays off, as in the
//!   browser today), with `macOptionIsMeta` off as `terminal.js` leaves it,
//!   plus Shift+Enter as ESC CR in one write (`shift-enter-key.js`). A golden
//!   table that the vendored bundle itself computes
//!   (`tests/fixtures/xterm-keys.jsonl`, generated by
//!   `crates/farhelm-ui/js-tests/xterm-key-table.js`) holds the two to the
//!   same bytes for every key code, modifier set, platform and cursor-key
//!   mode. xterm.js ignores the application keypad mode (DECKPAM): its
//!   function has no such input, and the keypad's keys send their digits, so
//!   this does too.
//!
//!   Which keydowns are sent at all is the grid client's decision, not this
//!   module's: the filters xterm.js's `_keyDown` applies around that
//!   function (a third-level shift, Option on a Mac or Ctrl+Alt and AltGraph
//!   on Windows, leaving the key to text input or sending nothing for F1 to
//!   F12 and the iOS arrows; capitals A to Z left to text input; the keydown
//!   after a dead key) run in the client's keydown port, which sends only
//!   the keydowns that survive them as `key` messages (`GridInput::Key`'s
//!   docs list them). The table pins the function, not those filters; the
//!   client's own tests pin them.
//! - **Text** is written as is, as UTF-8.
//! - **Paste**: Farhelm's own paste path (`term-bytes.js`'s
//!   `sanitizePastedText`, which drops ESC so the text cannot end a
//!   bracketed paste) followed by xterm.js's (`\r?\n` becomes CR; bracketed
//!   paste markers when the program set mode 2004), over the whole paste
//!   from its first part to the one marked `last`.
//! - **Mouse**: xterm.js's `CoreMouseService`, for the reporting modes the
//!   emulator tracks (1000, 1002, 1003) and xterm.js's encodings (the
//!   default one with its byte limit, and SGR 1006). On the alternate screen
//!   with mouse reporting off, a wheel step becomes an up or down arrow key,
//!   as xterm.js does there. The modes come from the emulator, which departs
//!   from xterm.js in two places. X10 mode 9 is not tracked, so a program
//!   that sets only it gets no reports. UTF-8 coordinates (1005), which
//!   xterm.js ignores (sending the default encoding, which a 1005 program
//!   misreads past column 94), are encoded as the program asked, unless SGR
//!   (1006) is set too: then SGR wins, whichever the program set first, as
//!   in tmux and today's xterm.js (the emulator keeps the two modes apart and
//!   reports SGR when both are set). De-duplicating motion is the client's
//!   job (`GridInput::Mouse`'s docs).
//! - **Focus**: `CSI I` and `CSI O`, only while the program set mode 1004.
//!
//! Every message's bytes fit one host `Input` frame (at most
//! [`MAX_INPUT`]); [`input_frames`] cuts anything longer and never cuts
//! inside one that fits, so a key's bytes (Shift+Enter's ESC CR among them)
//! always reach the host as one `Input`, which the host offers to the pty in
//! one write since it is at most `ATOMIC_INPUT` bytes (terminal host
//! SPEC.md, "Input").

use farhelm_proto::grid::{GridInput, MouseEventKind, modifiers};
use farhelm_terminal_emulator::{Modes, MouseEncoding, MouseReporting, Size};
use terminal_host::protocol::MAX_INPUT;

/// Opens a bracketed paste (mode 2004).
pub const PASTE_START: &[u8] = b"\x1b[200~";
/// Closes a bracketed paste.
pub const PASTE_END: &[u8] = b"\x1b[201~";

// ---- The encoder --------------------------------------------------------

/// The platform the viewer's keyboard is on, which changes a few keys'
/// bytes: xterm.js treats Option as a key of its own on a Mac (where it
/// types characters) and Alt as Meta (ESC plus the key) everywhere else.
///
/// The keys that differ are mostly ones a Mac client never sends as `key`
/// messages, but not all: Ctrl+Option with `_` or `@` sends US or NUL on a
/// Mac and ESC plus the key elsewhere, for example. Each `key` message says
/// which (its `mac` field), so [`InputEncoder`] reads it from the message.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeyPlatform {
    /// A Mac (xterm.js's `isMac`: `navigator.platform` is a Mac one).
    Mac,
    /// Anything else.
    Other,
}

/// A grid input message that breaks a rule spanning messages: a protocol
/// violation, on which the caller ends the attachment as on a malformed
/// message, writing [`InputEncoder::finish`]'s bytes as it does. The
/// encoder leaves the paste open for that.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum InputError {
    /// The parts of one paste must arrive with no other input between them
    /// (grid format, "Client to supervisor"); anything else would type into
    /// the middle of the pasted text, inside its bracketed-paste markers.
    #[error("a {0} message arrived in the middle of a paste")]
    PasteInterrupted(&'static str),
}

/// Turns one attachment's grid input messages into the bytes to write to its
/// terminal. One per attachment: the only state is the paste in progress,
/// which belongs to the attachment its parts arrive on.
#[derive(Debug, Default)]
pub struct InputEncoder {
    paste: Option<PasteInProgress>,
}

/// A paste whose first part has been encoded and whose `last` part has not.
#[derive(Debug)]
struct PasteInProgress {
    /// Whether the paste opened with [`PASTE_START`] and so must close with
    /// [`PASTE_END`]. Decided by the program's mode when the paste began and
    /// kept for the whole paste, so the markers always pair up even if the
    /// program changes the mode while the parts arrive.
    bracketed: bool,
    /// The text filter's state between parts.
    text: PasteText,
}

impl InputEncoder {
    /// An encoder for one attachment, with no paste in progress.
    pub fn new() -> InputEncoder {
        InputEncoder::default()
    }

    /// The bytes to write for one message, from the program's current
    /// `modes` and the terminal's current `size`; empty when the program
    /// gets nothing for it (a mouse event its mode does not report, focus
    /// without mode 1004, a key xterm.js sends nothing for).
    ///
    /// For a message that passed [`GridInput::validate`], the bytes fit one
    /// `Input` frame. `size` matters only for mouse events: one past the
    /// current screen (the screen shrank after the client sent it) is
    /// dropped, as xterm.js drops one outside its grid.
    pub fn encode(
        &mut self,
        input: &GridInput,
        modes: &Modes,
        size: Size,
    ) -> Result<Vec<u8>, InputError> {
        if let Some(kind) = interrupting_kind(input)
            && self.paste.is_some()
        {
            return Err(InputError::PasteInterrupted(kind));
        }
        Ok(match input {
            GridInput::Key {
                key,
                code,
                kc,
                mods,
                mac,
            } => encode_key(
                key,
                code,
                *kc,
                *mods,
                modes.application_cursor,
                if *mac {
                    KeyPlatform::Mac
                } else {
                    KeyPlatform::Other
                },
            ),
            GridInput::Text { data } => data.as_bytes().to_vec(),
            GridInput::Paste { data, last } => self.encode_paste(data, *last, modes),
            GridInput::Mouse {
                kind,
                button,
                x,
                y,
                mods,
            } => encode_mouse(*kind, *button, *x, *y, *mods, modes, size),
            GridInput::Focus { focused } => encode_focus(*focused, modes),
        })
    }

    /// Whether a paste has begun and its `last` part has not arrived.
    ///
    /// While it is true, nothing else may be written to the program: in a
    /// bracketed paste the program would read it as pasted text (a query
    /// answer would go unanswered and land in the paste, a prompt would be
    /// pasted rather than sent), and in any paste it would land between the
    /// pasted characters. The encoder refuses viewer input meanwhile
    /// ([`InputError::PasteInterrupted`]), but it cannot see the
    /// supervisor's own writes to the terminal; the grid sender holds those
    /// (emulator query answers, prompt sends) until this turns false, or
    /// until it has written [`InputEncoder::finish`]'s bytes.
    pub fn paste_open(&self) -> bool {
        self.paste.is_some()
    }

    /// The bytes to write when the attachment ends: [`PASTE_END`] if it
    /// ended in the middle of a bracketed paste, so the program is not left
    /// reading everything after as pasted text; otherwise nothing. Forgets
    /// the paste either way, including a held start of a marker, which an
    /// abandoned paste has no use for.
    pub fn finish(&mut self) -> Option<&'static [u8]> {
        match self.paste.take() {
            Some(PasteInProgress {
                bracketed: true, ..
            }) => Some(PASTE_END),
            _ => None,
        }
    }

    /// One part of a paste: the opening marker with its first part, the
    /// closing one with its last, the text sanitized and its line endings
    /// converted in between.
    fn encode_paste(&mut self, data: &str, last: bool, modes: &Modes) -> Vec<u8> {
        let mut out = Vec::with_capacity(data.len() + PASTE_START.len() + PASTE_END.len());
        let mut paste = match self.paste.take() {
            Some(paste) => paste,
            // Today's paste path drops an empty paste before xterm.js could
            // write a pair of markers around nothing.
            None if data.is_empty() && last => return out,
            None => {
                let bracketed = modes.bracketed_paste;
                if bracketed {
                    out.extend_from_slice(PASTE_START);
                }
                PasteInProgress {
                    bracketed,
                    text: PasteText::default(),
                }
            }
        };
        paste.text.push(data.as_bytes(), &mut out);
        if !last {
            self.paste = Some(paste);
            return out;
        }
        paste.text.end(&mut out);
        if paste.bracketed {
            out.extend_from_slice(PASTE_END);
        }
        out
    }
}

/// The message kind a paste in progress refuses, or `None` for a paste part.
fn interrupting_kind(input: &GridInput) -> Option<&'static str> {
    match input {
        GridInput::Key { .. } => Some("key"),
        GridInput::Text { .. } => Some("text"),
        GridInput::Paste { .. } => None,
        GridInput::Mouse { .. } => Some("mouse"),
        GridInput::Focus { .. } => Some("focus"),
    }
}

/// Cut bytes into `Input` frames of at most [`MAX_INPUT`] bytes. Bytes that
/// fit one frame stay one frame, so a small input such as Shift+Enter's ESC
/// CR is never split; nothing comes out for no bytes, since an `Input`
/// carries at least one.
pub fn input_frames(bytes: &[u8]) -> std::slice::Chunks<'_, u8> {
    bytes.chunks(MAX_INPUT)
}

// ---- Keys -----------------------------------------------------------------

const ESC: &str = "\x1b";

/// The bytes today's terminal sends for a keydown it sends a sequence for:
/// xterm.js's `evaluateKeyboardEvent(ev, applicationCursor, isMac, false)`,
/// and ESC before the CR of a Shift+Enter, as `shift-enter-key.js` merges
/// it. Empty where that function gives no sequence.
///
/// Whether xterm.js would send the sequence at all is not decided here:
/// `_keyDown` drops or leaves to text input some keydowns the function
/// gives a sequence for (a third-level shift, a lone capital, the keydown
/// after a dead key), and the grid client applies those filters before it
/// sends a `key` message (module docs, "Keys").
///
/// `key`, `code` and `kc` are the browser's `key`, `code` and `keyCode`;
/// `mods` is the grid format's [`modifiers`] bit set, which is xterm.js's
/// own modifier number. Where xterm.js measures `key` in UTF-16 code units
/// or slices `code`, so does this, and a lone surrogate it would produce
/// becomes U+FFFD as the page's `TextEncoder` makes it.
///
/// Shift+Enter is recognized as `shiftEnterKeyAction` does, by `key` and
/// exactly the Shift modifier. That function also refuses the chord under
/// AltGraph and during composition; neither reaches the supervisor (the
/// grid client sends no composing keys, and `mods` has no AltGraph bit), so
/// this assumes neither.
pub fn encode_key(
    key: &str,
    code: &str,
    kc: u32,
    mods: u8,
    application_cursor: bool,
    platform: KeyPlatform,
) -> Vec<u8> {
    let Some(mut sent) = xterm_key(key, code, kc, mods, application_cursor, platform) else {
        return Vec::new();
    };
    if key == "Enter" && mods == modifiers::SHIFT && sent.starts_with('\r') {
        sent.insert_str(0, ESC);
    }
    sent.into_bytes()
}

/// A port of the vendored xterm.js 6.0.0's `evaluateKeyboardEvent`, case for
/// case, returning the `key` it computes: the sequence for a keydown, or
/// `None` where it sends nothing (including Shift+PageUp/PageDown, which
/// scroll locally, and Cmd+A on a Mac, which selects locally). Kept in the
/// original's shape rather than simplified, since its whole value is being
/// the same function; the golden table holds it to the original.
fn xterm_key(
    key: &str,
    code: &str,
    kc: u32,
    mods: u8,
    application_cursor: bool,
    platform: KeyPlatform,
) -> Option<String> {
    let shift = mods & modifiers::SHIFT != 0;
    let alt = mods & modifiers::ALT != 0;
    let ctrl = mods & modifiers::CTRL != 0;
    let meta = mods & modifiers::META != 0;
    // xterm's modifier parameter: 1 plus the modifier bits.
    let param = u32::from(mods & modifiers::ALL) + 1;
    let modified = param > 1;
    // Cursor keys, Home and End: a modified form, else SS3 under
    // application cursor keys, else CSI.
    let cursor = |letter: char| -> String {
        if modified {
            format!("{ESC}[1;{param}{letter}")
        } else if application_cursor {
            format!("{ESC}O{letter}")
        } else {
            format!("{ESC}[{letter}")
        }
    };
    // The iOS arrow names, which ignore modifiers.
    let ios_arrow = |letter: char| -> String {
        if application_cursor {
            format!("{ESC}O{letter}")
        } else {
            format!("{ESC}[{letter}")
        }
    };
    let sent = match kc {
        0 => match key {
            "UIKeyInputUpArrow" => ios_arrow('A'),
            "UIKeyInputLeftArrow" => ios_arrow('D'),
            "UIKeyInputRightArrow" => ios_arrow('C'),
            "UIKeyInputDownArrow" => ios_arrow('B'),
            _ => return None,
        },
        // Backspace.
        8 => {
            let erase = if ctrl { "\x08" } else { "\x7f" };
            if alt {
                format!("{ESC}{erase}")
            } else {
                erase.to_owned()
            }
        }
        // Tab.
        9 => {
            if shift {
                format!("{ESC}[Z")
            } else {
                "\t".to_owned()
            }
        }
        // Enter.
        13 => {
            if alt {
                format!("{ESC}\r")
            } else {
                "\r".to_owned()
            }
        }
        // Escape.
        27 => {
            if alt {
                format!("{ESC}{ESC}")
            } else {
                ESC.to_owned()
            }
        }
        // The arrows, which xterm.js leaves to the browser under Meta.
        37..=40 if meta => return None,
        37 => cursor('D'),
        39 => cursor('C'),
        38 => cursor('A'),
        40 => cursor('B'),
        // Insert.
        45 => {
            if shift || ctrl {
                return None;
            }
            format!("{ESC}[2~")
        }
        // Delete.
        46 => {
            if modified {
                format!("{ESC}[3;{param}~")
            } else {
                format!("{ESC}[3~")
            }
        }
        36 => cursor('H'),
        35 => cursor('F'),
        // Page Up and Page Down: Shift scrolls the local view.
        33 | 34 => {
            let number = if kc == 33 { 5 } else { 6 };
            if shift {
                return None;
            } else if ctrl {
                format!("{ESC}[{number};{param}~")
            } else {
                format!("{ESC}[{number}~")
            }
        }
        // F1 to F4.
        112..=115 => {
            let letter = ['P', 'Q', 'R', 'S'][(kc - 112) as usize];
            if modified {
                format!("{ESC}[1;{param}{letter}")
            } else {
                format!("{ESC}O{letter}")
            }
        }
        // F5 to F12.
        116..=123 => {
            let number = [15, 17, 18, 19, 20, 21, 23, 24][(kc - 116) as usize];
            if modified {
                format!("{ESC}[{number};{param}~")
            } else {
                format!("{ESC}[{number}~")
            }
        }
        _ => return other_key(key, code, kc, shift, alt, ctrl, meta, platform),
    };
    Some(sent)
}

/// `evaluateKeyboardEvent`'s default case: every key code the switch does
/// not name.
#[allow(clippy::too_many_arguments)]
fn other_key(
    key: &str,
    code: &str,
    kc: u32,
    shift: bool,
    alt: bool,
    ctrl: bool,
    meta: bool,
    platform: KeyPlatform,
) -> Option<String> {
    let is_mac = platform == KeyPlatform::Mac;
    if ctrl && !shift && !alt && !meta {
        // Ctrl alone: the C0 control characters.
        let control = match kc {
            65..=90 => kc - 64,
            32 => 0,
            51..=55 => kc - 51 + 27,
            56 => 0x7f,
            219 => 0x1b,
            220 => 0x1c,
            221 => 0x1d,
            _ => return None,
        };
        return char::from_u32(control).map(String::from);
    }
    // `(isMac && !macOptionIsMeta) || !alt || meta`, with `macOptionIsMeta`
    // off: unless this is Alt (and not Meta) off a Mac, Alt is not Meta.
    if is_mac || !alt || meta {
        if is_mac && !alt && !ctrl && !shift && meta {
            // Cmd alone on a Mac: Cmd+A selects locally, the rest are the
            // browser's.
            return None;
        }
        if !key.is_empty() && !ctrl && !alt && !meta && kc >= 48 && utf16_len(key) == 1 {
            // A key that types exactly one character (one UTF-16 unit).
            return Some(key.to_owned());
        }
        if !key.is_empty() && ctrl {
            return match key {
                "_" => Some("\x1f".to_owned()),
                "@" => Some("\0".to_owned()),
                _ => None,
            };
        }
        return None;
    }
    // Alt as Meta: ESC and the key's character on a US layout.
    if let Some((plain, shifted)) = alt_key_mapping(kc) {
        return Some(format!("{ESC}{}", if shift { shifted } else { plain }));
    }
    if (65..=90).contains(&kc) {
        let unit = if ctrl { kc - 64 } else { kc + 32 };
        let mut character = char::from_u32(unit)?;
        if shift {
            character = character.to_ascii_uppercase();
        }
        return Some(format!("{ESC}{character}"));
    }
    if kc == 32 {
        return Some(format!("{ESC}{}", if ctrl { "\0" } else { " " }));
    }
    if key == "Dead" && code.starts_with("Key") {
        // The dead key's letter, from `code.slice(3, 4)`: one UTF-16 unit.
        let unit: Vec<u16> = code.encode_utf16().skip(3).take(1).collect();
        let letter = String::from_utf16_lossy(&unit);
        let letter = if shift { letter } else { letter.to_lowercase() };
        return Some(format!("{ESC}{letter}"));
    }
    None
}

/// xterm.js's `KEYCODE_KEY_MAPPINGS`: the unshifted and shifted character of
/// each US-layout key that Alt (as Meta) sends after ESC.
fn alt_key_mapping(kc: u32) -> Option<(&'static str, &'static str)> {
    Some(match kc {
        48 => ("0", ")"),
        49 => ("1", "!"),
        50 => ("2", "@"),
        51 => ("3", "#"),
        52 => ("4", "$"),
        53 => ("5", "%"),
        54 => ("6", "^"),
        55 => ("7", "&"),
        56 => ("8", "*"),
        57 => ("9", "("),
        186 => (";", ":"),
        187 => ("=", "+"),
        188 => (",", "<"),
        189 => ("-", "_"),
        190 => (".", ">"),
        191 => ("/", "?"),
        192 => ("`", "~"),
        219 => ("[", "{"),
        220 => ("\\", "|"),
        221 => ("]", "}"),
        222 => ("'", "\""),
        _ => return None,
    })
}

/// A string's JavaScript `length`: its UTF-16 code units.
fn utf16_len(text: &str) -> usize {
    text.encode_utf16().count()
}

// ---- Paste ----------------------------------------------------------------

/// The pasted text between the markers, made from the parts as they arrive:
/// Farhelm's sanitizing and then xterm.js's line-ending conversion, carried
/// across parts so that a paste comes out the same however it was split.
///
/// - Sanitizing is `term-bytes.js`'s `sanitizePastedText`,
///   `text.replace(/\x1b\[201~|\x1b/g, "")`: every end-of-paste marker goes
///   whole and every other ESC alone, so pasted text can never close the
///   bracketed paste around it and have the rest run as typed commands.
///   Today's page applies it before handing the text to xterm.js, and the
///   grid client does too; applying it again changes nothing (the first pass
///   leaves no ESC). It is applied here as well because the supervisor now
///   writes the markers, so the guarantee that pasted text stays inside them
///   belongs here.
/// - Conversion is xterm.js's `prepareTextForTerminal`,
///   `text.replace(/\r?\n/g, "\r")`: every CRLF and every lone LF becomes
///   one CR, so a pasted line ends the way a typed Enter does.
///
/// The grid client never splits a CRLF, and the format does not forbid
/// splitting a marker after its ESC; carrying both across parts is simpler
/// than refusing either split.
#[derive(Debug, Default)]
struct PasteText {
    /// The start of a possible end-of-paste marker at the end of what has
    /// arrived (ESC and up to four bytes of `[201~`), held until the next
    /// bytes say whether it is one. Never empty except as "nothing held".
    held: Vec<u8>,
    /// The last byte passed on was a CR from the text, so an LF next belongs
    /// to it and is dropped.
    after_cr: bool,
}

impl PasteText {
    /// Filter one part's bytes into `out`.
    fn push(&mut self, data: &[u8], out: &mut Vec<u8>) {
        for &byte in data {
            self.byte(byte, out);
        }
    }

    /// The paste's last part has arrived: a held prefix was not a marker, so
    /// its ESC goes as a lone ESC would and the rest is ordinary text.
    fn end(&mut self, out: &mut Vec<u8>) {
        let held = std::mem::take(&mut self.held);
        for &byte in held.iter().skip(1) {
            self.emit(byte, out);
        }
    }

    fn byte(&mut self, byte: u8, out: &mut Vec<u8>) {
        if self.held.is_empty() {
            if byte == 0x1b {
                self.held.push(byte);
            } else {
                self.emit(byte, out);
            }
            return;
        }
        self.held.push(byte);
        if self.held == PASTE_END {
            self.held.clear();
        } else if !PASTE_END.starts_with(&self.held) {
            // Not a marker after all: the regex would have dropped the ESC
            // alone, so what followed it is read again from the start (it
            // may hold the next ESC).
            let rest = std::mem::take(&mut self.held);
            for &byte in &rest[1..] {
                self.byte(byte, out);
            }
        }
    }

    /// Pass one sanitized byte on, converting line endings.
    fn emit(&mut self, byte: u8, out: &mut Vec<u8>) {
        match byte {
            b'\n' if self.after_cr => {}
            b'\n' => out.push(b'\r'),
            other => out.push(other),
        }
        self.after_cr = byte == b'\r';
    }
}

// ---- Mouse ----------------------------------------------------------------

/// xterm.js's button numbers (`CoreMouseButton`).
const BUTTON_NONE: u8 = 3;
const BUTTON_WHEEL: u8 = 4;

/// xterm.js's actions (`CoreMouseAction`); wheel steps reuse up and down.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Action {
    Up,
    Down,
    Move,
}

/// The bytes for one mouse event, following xterm.js's `CoreMouseService`
/// from the point where it has a cell, a button and an action: the event
/// must be on the screen, the program's reporting mode must report it, and
/// the encoding must be able to express it; otherwise nothing.
///
/// A wheel step with mouse reporting off is the exception: on the alternate
/// screen it is an up or down arrow key, one per step, as xterm.js sends for
/// a screen with no scrollback (honoring application cursor keys, ignoring
/// modifiers and the event's position, and regardless of mode 1007, which
/// xterm.js does not implement); on the normal screen it is the viewer's own
/// scrolling and sends nothing.
fn encode_mouse(
    kind: MouseEventKind,
    button: i8,
    x: u16,
    y: u16,
    mods: u8,
    modes: &Modes,
    size: Size,
) -> Vec<u8> {
    if modes.mouse_reporting == MouseReporting::Off {
        if kind == MouseEventKind::Wheel && modes.alternate_screen {
            let letter = if button == 0 { 'A' } else { 'B' };
            let intro = if modes.application_cursor { 'O' } else { '[' };
            return format!("{ESC}{intro}{letter}").into_bytes();
        }
        return Vec::new();
    }
    if x >= size.columns || y >= size.lines {
        return Vec::new();
    }
    // Buttons outside the format's range never pass `GridInput::validate`;
    // treating them as no button keeps this total.
    let held = u8::try_from(button).ok().filter(|b| *b <= 2);
    let (button, action) = match kind {
        MouseEventKind::Down => (held.unwrap_or(BUTTON_NONE), Action::Down),
        MouseEventKind::Up => (held.unwrap_or(BUTTON_NONE), Action::Up),
        MouseEventKind::Move => (held.unwrap_or(BUTTON_NONE), Action::Move),
        // Wheel up is xterm.js's "up" action, wheel down its "down".
        MouseEventKind::Wheel if button == 0 => (BUTTON_WHEEL, Action::Up),
        MouseEventKind::Wheel => (BUTTON_WHEEL, Action::Down),
    };
    // `triggerMouseEvent`: a press or release needs a button.
    if button == BUTTON_NONE && action != Action::Move {
        return Vec::new();
    }
    // The protocol's `restrict`: 1000 reports no motion, 1002 only motion
    // with a button held, 1003 everything.
    let reported = match modes.mouse_reporting {
        MouseReporting::Off => false,
        MouseReporting::Clicks => action != Action::Move,
        MouseReporting::Drag => action != Action::Move || button != BUTTON_NONE,
        MouseReporting::Motion => true,
    };
    if !reported {
        return Vec::new();
    }
    // xterm.js's report coordinates are 1-based.
    let column = u32::from(x) + 1;
    let row = u32::from(y) + 1;
    match modes.mouse_encoding {
        MouseEncoding::Sgr => {
            let code = event_code(button, action, mods, true);
            let last = if action == Action::Up && button != BUTTON_WHEEL {
                'm'
            } else {
                'M'
            };
            format!("{ESC}[<{code};{column};{row}{last}").into_bytes()
        }
        MouseEncoding::Default => {
            let values = [
                event_code(button, action, mods, false) + 32,
                column + 32,
                row + 32,
            ];
            // One byte each: past 255 (a column or row past 223) the
            // encoding cannot say it, and xterm.js sends nothing.
            let mut out = b"\x1b[M".to_vec();
            for value in values {
                let Ok(byte) = u8::try_from(value) else {
                    return Vec::new();
                };
                out.push(byte);
            }
            out
        }
        MouseEncoding::Utf8 => {
            // The default encoding's values, each written as a UTF-8
            // character (xterm's mode 1005). The largest grid keeps every
            // value under 2048, so each takes one or two bytes.
            let values = [
                event_code(button, action, mods, false) + 32,
                column + 32,
                row + 32,
            ];
            let mut out = format!("{ESC}[M");
            for value in values {
                let Some(character) = char::from_u32(value) else {
                    return Vec::new();
                };
                out.push(character);
            }
            out.into_bytes()
        }
    }
}

/// xterm.js's event code (`h` in `CoreMouseService`): the button, the
/// modifiers (Shift 4, Alt 8, Ctrl 16; Meta is not reported), 32 for motion
/// and 64 for the wheel. A release is button 3 in the encodings that cannot
/// say which button was released; SGR keeps the button and marks the
/// release with its final `m` instead.
fn event_code(button: u8, action: Action, mods: u8, sgr: bool) -> u32 {
    let mut code = 0;
    if mods & modifiers::CTRL != 0 {
        code |= 16;
    }
    if mods & modifiers::SHIFT != 0 {
        code |= 4;
    }
    if mods & modifiers::ALT != 0 {
        code |= 8;
    }
    if button == BUTTON_WHEEL {
        code |= 64;
        if action == Action::Down {
            code |= 1;
        }
        return code;
    }
    code |= u32::from(button & 3);
    match action {
        Action::Move => code |= 32,
        Action::Up if !sgr => code |= 3,
        Action::Up | Action::Down => {}
    }
    code
}

// ---- Focus ----------------------------------------------------------------

/// `CSI I` when the terminal gains focus and `CSI O` when it loses it, only
/// while the program asked for them (mode 1004).
fn encode_focus(focused: bool, modes: &Modes) -> Vec<u8> {
    if !modes.focus_reporting {
        return Vec::new();
    }
    if focused {
        b"\x1b[I".to_vec()
    } else {
        b"\x1b[O".to_vec()
    }
}


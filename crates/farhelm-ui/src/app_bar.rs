/// Open one of Farhelm's own pages through the page's shared link opener
/// (`terminal-links.js`), which knows how to reach the system browser from
/// the desktop webview and opens a new tab elsewhere. Callers pass a
/// constant, so it needs none of the opener callers' validation.
///
/// That opener is its own script asset, loaded asynchronously, so a click
/// right after the page loads can arrive before it exists. The fallback
/// repeats the opener's two branches (navigate the `dioxus:` page, which the
/// desktop shell turns into a system-browser open; otherwise a `noopener`
/// tab) so the item never silently does nothing.
pub(crate) fn open_external_page(url: &'static str) {
    let url = serde_json::to_string(url).expect("a string always serializes");
    document::eval(&format!(
        "(() => {{
            const url = {url};
            if (window.farhelmTerminalLinks) {{
                window.farhelmTerminalLinks.openTerminalUrl(url);
            }} else if (window.location.protocol === 'dioxus:') {{
                window.location.assign(url);
            }} else {{
                window.open(url, '_blank', 'noopener');
            }}
        }})();"
    ));
}

// ===== The bar menus ========================================================
//
// Each menu in the sidebar's bar (the `?` menu, and the update menu opened
// from the red version readout) is a toggle inside the bar and a flyout
// that is the bar's next SIBLING, never inside it. The bar is sticky, so it
// is a stacking context, and it lives inside `.app-sidebar`, the scroll
// container. WebKit clips a fixed-position element to an overflow ancestor
// whenever the element's stacking context sits inside that ancestor (WebKit
// bug 160953), so a flyout inside the bar was painted only up to the
// sidebar's right edge: in the macOS app the help menu showed as its
// pointer and a few pixels. As a sibling, like the row menus' flyouts, no
// ancestor below the root forms a stacking context.
//
// Because toggle and flyout are separate components in separate places,
// their shared state ([`BarMenuState`]) is owned by `AppBar`, which renders
// both. They reuse the row menus' machinery (`menu_panel`) so they behave
// like them: arrow keys, Home/End, Escape and Tab inside the menu, focus
// back on the toggle when it closes, the same side flyout and pointer, and
// the shared outside-pointer dismissal, which reaches each menu through its
// own relay button keyed `bar:<name>`. Their elements carry the host row
// menu's panel and item classes for the shared look, plus `bar-menu-*`
// classes. Both the toggle's wrapper and the flyout carry
// `data-bar-menu="<name>"`: the dismissal derives the relay key from
// whichever encloses the open panel, and the focus helper finds the toggle
// under the one that holds it.

/// One bar menu's state, shared by its toggle and its flyout. Besides its
/// name, every field is a signal or callback created by [`use_bar_menu`] in
/// `AppBar`, so the whole thing is `Copy` and stays the same across renders.
#[derive(Clone, Copy)]
struct BarMenuState {
    /// The menu's name: its `data-bar-menu` marker and accessible name.
    name: &'static str,
    open: Signal<bool>,
    /// The layout epoch the open menu was measured under. Its coordinates
    /// are a snapshot, so a later resize or scroll closes the menu, as it
    /// does the session and host menus, rather than leaving it detached
    /// from its toggle (the bar's controls move at the narrow-window
    /// breakpoint).
    opened_epoch: Signal<u64>,
    toggle_handle: Signal<Option<Rc<MountedData>>>,
    placement: Signal<PanelPlacement>,
    item_handles: Signal<HashMap<BarMenuItem, Rc<MountedData>>>,
    menu_focus: Signal<Option<usize>>,
    menu_requested: Signal<Option<usize>>,
    open_intent: Signal<Option<MenuOpenIntent>>,
    focus_queue: MenuFocusQueue,
    open_generation: Signal<u64>,
    close_menu: Callback<()>,
    instance: u64,
}

impl PartialEq for BarMenuState {
    /// The signals are created once per menu, so identity is equality.
    fn eq(&self, other: &Self) -> bool {
        self.name == other.name && self.open == other.open
    }
}

impl BarMenuState {
    /// The menu wiring `menu_panel`'s key handling and focus helpers take.
    fn wiring(self, order: BarMenuOrder) -> MenuWiring<BarMenuItem, (), { BAR_MENU_ITEMS.len() }> {
        MenuWiring {
            order,
            handles: self.item_handles,
            focus: self.focus_queue,
            generation: self.open_generation,
            focused: self.menu_focus,
            requested: self.menu_requested,
            open_intent: self.open_intent,
            close_menu: self.close_menu,
            instance: self.instance,
        }
    }

    /// Measure the toggle for the flyout's placement, unless a newer open
    /// has started since.
    fn spawn_measurement(self) {
        let mut placement = self.placement;
        let generation = (self.open_generation)();
        let toggle_handle = self.toggle_handle;
        let open_generation = self.open_generation;
        spawn(async move {
            let measured = match toggle_handle.peek().clone() {
                Some(handle) => handle.get_client_rect().await.ok(),
                None => None,
            };
            if let Some(outcome) =
                measurement_outcome(generation, *open_generation.peek(), measured)
            {
                placement.set(outcome);
            }
        });
    }

    /// Open the menu fresh, as the row menus do.
    fn begin_open(self, intent: MenuOpenIntent, layout_epoch: ReadSignal<u64>) {
        let Self {
            mut open,
            mut opened_epoch,
            mut placement,
            mut item_handles,
            mut menu_focus,
            mut menu_requested,
            mut open_intent,
            mut open_generation,
            focus_queue,
            ..
        } = self;
        open_generation += 1;
        placement.set(PanelPlacement::Unmeasured);
        item_handles.write().clear();
        cancel_menu_focus(focus_queue);
        menu_focus.set(None);
        menu_requested.set(None);
        open_intent.set(Some(intent));
        opened_epoch.set(*layout_epoch.peek());
        install_row_menu_outside_dismiss();
        open.set(true);
        self.spawn_measurement();
    }
}

/// Create one bar menu's state, with the two effects every such menu needs:
/// close when the layout moves, and on close forget the focus bookkeeping
/// and hand focus back to the toggle if it was inside the menu.
/// The returned registration also admits causes local to this menu's anchor.
fn use_bar_menu(layout_epoch: ReadSignal<u64>, name: &'static str) -> (BarMenuState, Registration) {
    let mut open = use_signal(|| false);
    let opened_epoch = use_signal(|| *layout_epoch.peek());
    let mut menu_focus = use_signal(|| None::<usize>);
    let mut menu_requested = use_signal(|| None::<usize>);
    let mut open_intent = use_signal(|| None::<MenuOpenIntent>);
    let mut item_handles = use_signal(HashMap::new);
    let focus_queue = MenuFocusQueue {
        target: use_signal(|| None),
        in_flight: use_signal(|| None),
        draining: use_signal(|| false),
    };
    let state = BarMenuState {
        name,
        open,
        opened_epoch,
        toggle_handle: use_signal(|| None),
        placement: use_signal(|| PanelPlacement::Unmeasured),
        item_handles,
        menu_focus,
        menu_requested,
        open_intent,
        focus_queue,
        open_generation: use_signal(|| 0_u64),
        close_menu: use_callback(move |()| open.set(false)),
        instance: use_menu_instance(),
    };
    let registration = use_registration(
        use_context::<MovementOwner>(),
        Interest::new(AnchorRegion::AppBar),
        move || (*open.peek()).then(|| name.to_string()),
        move || state.close_menu.call(()),
    );
    // Retain this menu's own epoch continuation: a pending effect for the
    // epoch captured by begin_open must not dismiss that fresh measurement.
    let layout_registration = registration.clone();
    use_effect(move || {
        let epoch = layout_epoch();
        if *open.peek() && epoch != *opened_epoch.peek() {
            layout_registration.close_if_open();
        }
    });
    use_effect(move || {
        if open() {
            return;
        }
        cancel_menu_focus(focus_queue);
        let was_inside = menu_focus.peek().is_some();
        menu_focus.set(None);
        menu_requested.set(None);
        open_intent.set(None);
        item_handles.write().clear();
        if was_inside {
            focus_menu_toggle("data-bar-menu", name, ".bar-menu-toggle");
        }
    });
    (state, registration)
}

/// One mounted status producer's last render and undelivered opening cause.
/// This is metadata for the Update anchor, not another owner of updater feedback.
#[derive(Default)]
struct RenderedUpdateStatus {
    current: Option<InlinePresentation>,
    pending_generation: Option<u64>,
}

/// Close only the Update opening that existed when visible status changed.
///
/// Capture happens during the status child's render, before its changed DOM is
/// committed. Delivery uses the existing registration after commit. The pending
/// generation preserves A→B→A renders even when Dioxus deduplicates their effect;
/// a synchronous reopen advances the generation and rejects that earlier cause.
/// Initial render seeds the baseline, and unchanged words never acquire a cause.
fn use_update_status_movement(
    menu: BarMenuState,
    registration: Registration,
) -> (Callback<InlinePresentation>, Callback<()>) {
    let rendered = use_hook(|| Rc::new(RefCell::new(RenderedUpdateStatus::default())));
    let captured = rendered.clone();
    let on_render = use_callback(move |presentation| {
        let mut captured = captured.borrow_mut();
        if captured
            .current
            .replace(presentation)
            .is_some_and(|old| old != presentation)
        {
            captured.pending_generation = (*menu.open.peek()).then(|| *menu.open_generation.peek());
        }
    });
    let on_commit = use_callback(move |()| {
        let pending = rendered.borrow_mut().pending_generation.take();
        if pending.is_some_and(|generation| {
            *menu.open.peek() && generation == *menu.open_generation.peek()
        }) {
            registration.close_if_open();
        }
    });
    (on_render, on_commit)
}

/// A bar menu's toggle, inside the bar, with the hidden relay the
/// outside-pointer dismissal clicks.
#[component]
fn BarMenuToggle(
    layout_epoch: ReadSignal<u64>,
    menu: BarMenuState,
    /// What the menu offers; shown in [`BAR_MENU_ITEMS`] order.
    items: Vec<BarMenuItem>,
    /// The toggle's classes, besides the shared `bar-menu-toggle`.
    toggle_class: &'static str,
    toggle_label: String,
    toggle_tooltip: String,
    /// Hide the toggle (and so the whole menu) while it has nothing to
    /// offer. Hidden rather than unmounted: focus moves into a menu through
    /// tasks spawned by its toggle and flyout components, and unmounting
    /// either would cancel such a task midway and leave the shared focus
    /// queue marked busy for good.
    #[props(default)]
    hidden: bool,
    /// The toggle's content.
    children: Element,
) -> Element {
    let order = BarMenuOrder::pack(BAR_MENU_ITEMS, |item| items.contains(&item));
    let wiring = menu.wiring(order);
    let mut open = menu.open;
    let mut toggle_handle = menu.toggle_handle;
    rsx! {
        span { class: "app-bar-menu", "data-bar-menu": menu.name, hidden,
            button {
                r#type: "button",
                class: "{toggle_class} bar-menu-toggle",
                aria_label: "{toggle_label}",
                "data-tooltip": "{toggle_tooltip}",
                aria_haspopup: "menu",
                aria_expanded: open(),
                onkeydown: move |evt| {
                    if !open() {
                        let Some(intent) = closed_toggle_key_intent(&evt.key()) else {
                            return;
                        };
                        evt.prevent_default();
                        menu.begin_open(intent, layout_epoch);
                        return;
                    }
                    handle_menu_key(&evt, None, wiring, &());
                },
                onfocusin: move |_| forget_menu_focus(wiring),
                onmounted: move |element| {
                    toggle_handle.set(Some(element.data()));
                    if should_measure_on_mount(open(), *menu.placement.peek()) {
                        menu.spawn_measurement();
                    }
                },
                onclick: move |_| {
                    if open() {
                        open.set(false);
                    } else {
                        menu.begin_open(MenuOpenIntent::First, layout_epoch);
                    }
                },
                {children}
            }
            button {
                r#type: "button",
                class: ROW_MENU_OUTSIDE_RELAY,
                "data-row-menu": row_menu_relay_key("bar", menu.name),
                hidden: true,
                tabindex: "-1",
                onclick: move |_| open.set(false),
            }
        }
    }
}

/// Anchor the footer's Help menu from its bottom edge, rather than reserving
/// the much taller session menu's height above a shorter actual panel. The
/// same measured trigger and generation still own placement and focus.
fn footer_menu_placement(placement: PanelPlacement) -> (String, Option<String>) {
    let PanelPlacement::Measured(rect) = placement else {
        return (
            format!("{} bottom: auto;", session_menu_placement_style(placement)),
            session_menu_pointer_style(placement),
        );
    };
    let left = rect.max_x() + 10.0;
    let bottom = rect.max_y() + 4.0;
    let pointer = (rect.max_y() - rect.min_y()) / 2.0 - 1.0;
    (
        format!(
            "opacity: 1; pointer-events: auto; right: auto; top: auto; \
                 --menu-left: max(8px, min({left}px, calc(100vw - 254px))); \
                 left: var(--menu-left); \
                 --menu-bottom: max(8px, calc(100vh - {bottom}px)); \
                 bottom: var(--menu-bottom); \
                 max-width: calc(100vw - var(--menu-left) - 8px); \
                 max-height: calc(100vh - var(--menu-bottom) - 8px);"
        ),
        Some(format!(
            "top: auto; bottom: clamp(12px, {pointer}px, calc(100% - 18px));"
        )),
    )
}

/// A bar menu's flyout, the bar's next sibling (see the section note above
/// for why it must not be inside the bar), shown while the menu is open.
#[component]
fn BarMenuFlyout(
    menu: BarMenuState,
    /// What the menu offers; the same list its toggle was given.
    items: Vec<BarMenuItem>,
    on_choose: EventHandler<BarMenuItem>,
) -> Element {
    let order = BarMenuOrder::pack(BAR_MENU_ITEMS, |item| items.contains(&item));
    let wiring = menu.wiring(order);
    let mut open = menu.open;
    let mut menu_focus = menu.menu_focus;
    let (placement_style, pointer_style) = if menu.name == "help" {
        footer_menu_placement((menu.placement)())
    } else {
        (
            session_menu_placement_style((menu.placement)()),
            session_menu_pointer_style((menu.placement)()),
        )
    };
    let tab_stop = menu_focus()
        .and_then(|position| order.get(position))
        .or_else(|| order.get(0));
    let mut choose = move |item: BarMenuItem| {
        open.set(false);
        on_choose.call(item);
    };
    rsx! {
        if open() {
            div {
                class: "host-row-menu-flyout bar-menu-flyout",
                "data-bar-menu": menu.name,
                style: placement_style,
                if let Some(pointer_style) = pointer_style {
                    span { class: "host-row-menu-pointer", style: pointer_style, "aria-hidden": "true" }
                }
                div { class: "host-row-menu-panel bar-menu-panel",
                    crate::menu_panel::MenuHeader {
                        title: rsx! { if menu.name == "help" { "Help" } else { "Farhelm update" } },
                        summary: rsx! { if menu.name == "help" { "Farhelm guides and feedback" } else { "An installed update is ready" } },
                    }
                    div {
                        class: "host-row-menu-items session-row-menu-items",
                        role: "menu",
                        aria_label: menu.name,
                        // Rendered from the same list keyboard order is
                        // built from, so the two cannot drift apart.
                        for item in order.actions() {
                            button {
                                key: "{item.label()}",
                                r#type: "button",
                                class: "btn menu-item session-row-menu-item host-row-menu-item bar-menu-item",
                                "data-bar-menu-item": item.label(),
                                "data-menu-focus": crate::menu_panel::menu_item_focus_key(wiring, item),
                                "data-tooltip": item.tooltip(),
                                role: "menuitem",
                                tabindex: if tab_stop == Some(item) { "0" } else { "-1" },
                                onmounted: move |element| remember_menu_item(wiring, item, element.data()),
                                onfocusin: move |_| record_menu_item_focus(wiring, item),
                                onfocusout: move |_| menu_focus.set(None),
                                onkeydown: move |evt| handle_menu_key(&evt, order.position(item), wiring, &()),
                                onclick: move |_| choose(item),
                                crate::icons::ActionIcon { glyph: item.glyph(), class: "menu-icon session-row-menu-icon" }
                                crate::menu_panel::MenuItemCopy {
                                    label: rsx! { "{item.label()}" },
                                    description: rsx! { "{item.description()}" },
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

/// How long after the feedback dialog closes its success is announced: long
/// enough for the dialog's modal isolation to be released (one frame or
/// two), so the status region is in the accessibility tree when it changes.
const ANNOUNCE_AFTER_CLOSE_MS: u64 = 100;

/// Keep app-wide menu and dialog lifetimes independent of sidebar layout.
/// The top band holds wordmark/build identity; its sibling rail footer holds
/// settings and help. Flyouts and modals remain outside both stacking
/// contexts, and moving a trigger never remounts its pending work.
#[component]
pub(crate) fn AppBar(
    layout_epoch: ReadSignal<u64>,
    /// ListView owns presentation; this footer only hosts its persistent control.
    #[props(default = rsx! {})]
    hosts_toggle: Element,
    children: Element,
) -> Element {
    let mut settings_open = use_signal(|| false);
    let mut ssh_help_open = use_signal(|| false);
    let mut feedback_open = use_signal(|| false);
    let base = use_context::<crate::ApiBase>().0;
    let mut preferences = use_context::<crate::list::SharedPreferences>();
    let initial_welcome = use_context::<crate::welcome::WelcomeOnLoad>();
    let mut welcome_open = use_signal(move || *initial_welcome.0.peek());
    let mut welcome_from_load = use_signal(move || *initial_welcome.0.peek());
    // The success announcement lives here, outside the dialog: a status
    // region inserted together with its text is not reliably announced, and
    // the dialog closes itself moments after success. This one is always
    // mounted (visually hidden) and only changes its text.
    let mut feedback_notice = use_signal(String::new);
    // Set when a send succeeds; the announcement waits for the dialog to
    // close (see `close_feedback`).
    let mut pending_thanks = use_signal(|| false);
    // Record only the first-open card. A help-menu reopening is an explicit
    // request and does not write the shared seen setting again. Feedback takes
    // focus itself, so its handoff must not queue a competing toggle focus.
    let finish_welcome = Callback::new(move |open_feedback: bool| {
        let first_open = std::mem::take(&mut *welcome_from_load.write());
        if first_open {
            preferences.0.write().welcome_seen = Some(true);
            crate::api::store_preference(&base, crate::api::PreferenceValue::WelcomeSeen(true));
        }
        if open_feedback {
            crate::welcome::DIALOG.release();
        } else if first_open {
            // Initial reveal withheld terminal focus behind Welcome. Restore
            // only a selected, revealed terminal; an empty page has no opener.
            crate::welcome::DIALOG.close("window.farhelmTerm?.focusSelected();");
        } else {
            crate::welcome::DIALOG.close(
                &crate::modal_dialog::FocusTarget::new(".app-help-toggle", None, false).script(),
            );
        }
        welcome_open.set(false);
        if open_feedback {
            feedback_notice.set(String::new());
            feedback_open.set(true);
        }
    });
    let feedback_dialog = crate::modal_dialog::DialogHandle::new(crate::feedback::DIALOG_SELECTOR);
    let settings_dialog = crate::modal_dialog::DialogHandle::new(crate::settings::DIALOG_SELECTOR);
    let close_feedback = move |_| {
        feedback_dialog.close(crate::feedback::RETURN_FOCUS);
        feedback_open.set(false);
        // Announce a success only now: while the dialog is open its modal
        // isolation marks this status region inert, and a live region that
        // changes while inert (or that is already populated when it becomes
        // visible again) is not reliably announced. The short wait lets the
        // release of isolation land before the text changes.
        if std::mem::take(&mut *pending_thanks.write()) {
            spawn(async move {
                sleep_ms(ANNOUNCE_AFTER_CLOSE_MS).await;
                feedback_notice.set(crate::feedback::THANKS.to_string());
            });
        }
    };
    let close_settings = move |_| {
        settings_dialog.close(crate::settings::RETURN_FOCUS);
        settings_open.set(false);
    };
    let skew = skew::HELM_BUILD_SKEW.read();
    // A reported stamp is text the helm sent, so it goes through the same
    // display boundary every relayed value does (`peer.rs`): invisible and
    // direction-changing characters become visible escapes, and the element
    // is bidi-isolated. The client build takes the same path for uniformity.
    let version = display_peer(displayed_version(skew.as_ref()));
    // The feedback dialog sends the version as the helm or this build
    // reported it (fitted to its cap) and displays that same string
    // bidi-isolated (`peer-value`) rather than escaped. Invisible formatting
    // characters, if a build stamp ever held any, would therefore be sent
    // without showing; the stamp comes from the user's own helm.
    let sent_version = displayed_version(skew.as_ref()).to_string();
    // In a desktop app whose updater runs, the readout is also the update
    // marker (SPEC.md "Installation and updates"): red with an up-arrow, and
    // the update menu's toggle, while a newer version is installed, and its
    // hover carries the updater's state. Without an update waiting the desktop
    // version starts the same check as the help menu; the web stays plain text.
    let updater = use_app_updater();
    let readout = updater.as_ref().map(AppUpdater::readout);
    let control = crate::app_updater::readout_control(readout.as_ref());
    let update_ready = readout.as_ref().is_some_and(|readout| readout.update_ready);
    // Withdrawals and lost verification share a mark, but the hover carries
    // both reasons when they coexist. Neither should disappear behind a safe
    // waiting update's arrow.
    let version_warning = readout
        .as_ref()
        .is_some_and(|readout| readout.needs_reinstall || readout.withdrawn);
    let marks = readout
        .as_ref()
        .map(crate::app_updater::readout_marks)
        .unwrap_or_default();
    let reported = match skew.as_ref() {
        Some(Skew::Reported(stamp)) => Some(stamp.as_str()),
        Some(Skew::Silent) | None => None,
    };
    let version_tooltip =
        crate::app_updater::version_tooltip(skew::CLIENT_BUILD, reported, readout.as_ref());

    let (help_menu, _) = use_bar_menu(layout_epoch, "help");
    let (update_menu, update_registration) = use_bar_menu(layout_epoch, "update");
    let (status_rendered, status_committed) =
        use_update_status_movement(update_menu, update_registration);
    // The update menu's toggle is the red readout, which goes away when no
    // update waits any more (a newer check, a reinstall); an open update
    // menu must not outlive it.
    // The effect reads the updater's state itself (a signal), so it reruns
    // whenever that changes; a value captured from this render would not.
    let watched_updater = updater.clone();
    use_effect(move || {
        let ready = watched_updater
            .as_ref()
            .is_some_and(|updater| updater.readout().update_ready);
        let mut open = update_menu.open;
        if !ready && *open.peek() {
            open.set(false);
        }
    });
    let has_updater = updater.is_some();
    let help_items = help_menu_items(has_updater);
    let help_tooltip = if has_updater {
        "help: send feedback, open the documentation or release notes, get ssh 2FA help, show welcome, or check for updates"
    } else {
        "help: send feedback, open the documentation or release notes, get ssh 2FA help, or show welcome"
    };
    let help_updater = updater.clone();
    let update_updater = updater.clone();

    rsx! {
        div { class: "app-bar {crate::window_chrome::WINDOW_DRAG_SURFACE}",
            onmousedown: crate::window_chrome::window_surface_press,
            // Trusted, compile-time markup from the repository's own brand
            // files, never peer data, which is what makes inner HTML safe here.
            // The hidden variant takes no layout or accessibility-tree space.
            span { class: "app-wordmark app-wordmark-dark", dangerous_inner_html: WORDMARK_DARK_SVG }
            span { class: "app-wordmark app-wordmark-light", dangerous_inner_html: WORDMARK_LIGHT_SVG }
            crate::window_chrome::WindowDragRegion {}
            // Always mounted, hidden while no update waits (see
            // `BarMenuToggle`'s `hidden`); the check control shows instead.
            if updater.is_some() {
                BarMenuToggle {
                    layout_epoch,
                    menu: update_menu,
                    items: UPDATE_MENU_ITEMS.to_vec(),
                    toggle_class: "btn app-version app-version-update app-version-toggle peer-value",
                    // The visible text is the running version; the name
                    // leads with it so a screen reader announces what a
                    // sighted user sees.
                    toggle_label: "Farhelm {version}, update ready: {version_tooltip}",
                    toggle_tooltip: version_tooltip.clone(),
                    hidden: !update_ready,
                    // The warning mark and the arrow (see `readout_marks`);
                    // the warning's words are already in the label and
                    // hover through the readout.
                    for mark in marks.clone() {
                        span { class: mark.class, "aria-hidden": "true", "{mark.glyph}" }
                    }
                    span { dir: "ltr", "{version}" }
                }
            }
            if let crate::app_updater::ReadoutControl::Check { .. } = control {
                if let (Some(check_updater), Some(readout)) = (updater.clone(), readout.as_ref()) {
                    {crate::app_updater::check_readout(&version, &version_tooltip, readout,
                        EventHandler::new(move |_| check_updater.check_now()))}
                }
            }
            if control == crate::app_updater::ReadoutControl::Plain {
                span {
                    class: if version_warning { "app-version app-version-unverified peer-value" } else { "app-version peer-value" },
                    dir: "ltr",
                    "data-tooltip": "{version_tooltip}",
                    for mark in marks {
                        span { class: mark.class, "aria-hidden": "true", "{mark.glyph}" }
                    }
                    if version_warning {
                        span { class: "visually-hidden", "{version_tooltip}" }
                    }
                    "{version}"
                }
            }
            if let Some(updater) = updater.clone() {
                crate::app_updater::UpdateCheckStatus {
                    updater,
                    on_render: status_rendered,
                    on_commit: status_committed,
                }
            }
        }
        // Keep the caller's persistent content before the footer in DOM
        // order, so keyboard navigation reaches host choices before Settings.
        {children}
        // These triggers stay in AppBar's scope: moving chrome must not
        // replace the settings/help owners or their pending dialog work.
        div { class: "host-rail-footer",
            {hosts_toggle}
            button {
                r#type: "button",
                class: "btn btn-neutral app-settings-toggle",
                aria_label: "Settings",
                "data-tooltip": if has_updater {
                    "Settings: choices that apply to every host on this helm, and this app's automatic updates"
                } else {
                    "Settings: choices that apply to every host on this helm"
                },
                aria_haspopup: "dialog",
                onclick: move |_| settings_open.set(true),
                crate::icons::SettingsIcon {}
            }
            BarMenuToggle {
                layout_epoch,
                menu: help_menu,
                items: help_items.clone(),
                toggle_class: "btn btn-neutral app-help-toggle",
                toggle_label: "help",
                toggle_tooltip: help_tooltip,
                crate::icons::HelpIcon {}
            }
        }
        BarMenuFlyout {
            menu: help_menu,
            items: help_items,
            on_choose: move |item| match item {
                BarMenuItem::SendFeedback => {
                    feedback_notice.set(String::new());
                    feedback_open.set(true);
                }
                BarMenuItem::Documentation => open_external_page(DOCS_URL),
                BarMenuItem::ReleaseNotes => open_external_page(RELEASE_NOTES_URL),
                BarMenuItem::SshHelp => ssh_help_open.set(true),
                BarMenuItem::Welcome => {
                    welcome_from_load.set(false);
                    welcome_open.set(true);
                }
                BarMenuItem::CheckForUpdates => {
                    if let Some(updater) = &help_updater {
                        updater.check_now();
                    }
                }
                // The update menu's items; never in this menu's list.
                BarMenuItem::RestartToUpdate | BarMenuItem::WhatsNew => {}
            },
        }
        // Mounted whenever there is an updater, for the same reason as its
        // toggle; it shows nothing unless open, and the effect above closes
        // it once no update waits.
        if updater.is_some() {
            BarMenuFlyout {
                menu: update_menu,
                items: UPDATE_MENU_ITEMS.to_vec(),
                on_choose: move |item| match item {
                    BarMenuItem::RestartToUpdate => {
                        if let Some(updater) = &update_updater {
                            updater.restart_to_update();
                        }
                    }
                    BarMenuItem::WhatsNew => open_external_page(RELEASE_NOTES_URL),
                    // The help menu's items; never in this menu's list.
                    BarMenuItem::SendFeedback
                    | BarMenuItem::Documentation
                    | BarMenuItem::ReleaseNotes
                    | BarMenuItem::SshHelp
                    | BarMenuItem::Welcome
                    | BarMenuItem::CheckForUpdates => {}
                },
            }
        }
        if settings_open() {
            crate::settings::SettingsDialog { on_close: close_settings }
        }
        if ssh_help_open() {
            crate::ssh_help::SshHelpDialog {
                destination: None,
                on_close: move |_| {
                    crate::ssh_help::DIALOG.close(
                        &crate::modal_dialog::FocusTarget::new(".app-help-toggle", None, false).script(),
                    );
                    ssh_help_open.set(false);
                },
            }
        }
        if feedback_open() {
            crate::feedback::FeedbackDialog {
                version: sent_version,
                on_sent: move |_| pending_thanks.set(true),
                on_close: close_feedback,
            }
        }
        if welcome_open() {
            crate::welcome::WelcomeDialog {
                on_close: move |_| finish_welcome.call(false),
                on_feedback: move |_| finish_welcome.call(true),
            }
        }
        p { class: "visually-hidden feedback-notice", role: "status", "{feedback_notice}" }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::cell::Cell;

    /// Production handles exposed by the headless fixture after its hooks mount.
    #[derive(Clone, Copy)]
    struct StatusMenus {
        help: BarMenuState,
        update: BarMenuState,
        epoch: ReadSignal<u64>,
    }

    /// Own only render input and menu handles; no native updater or web stand-in
    /// is constructed. The production hooks supply registration and timing.
    #[derive(Clone, Default)]
    struct StatusFixture {
        presentation: Rc<Cell<InlinePresentation>>,
        menus: Rc<RefCell<Option<StatusMenus>>>,
    }

    /// Exercise the exact render-capture/effect boundary used by UpdateCheckStatus.
    /// The no-op document permits the ordinary opening path without a webview;
    /// geometry and actual keyboard focus are deliberately not asserted here.
    fn status_fixture(fixture: StatusFixture) -> Element {
        use_context_provider(MovementOwner::default);
        use_context_provider(|| Rc::new(document::NoOpDocument) as Rc<dyn document::Document>);
        let epoch = use_signal(|| 0_u64);
        let (help, _) = use_bar_menu(epoch.into(), "help");
        let (update, registration) = use_bar_menu(epoch.into(), "update");
        let (on_render, on_commit) = use_update_status_movement(update, registration);
        let presentation = fixture.presentation.get();
        crate::app_updater::use_inline_status_movement(presentation, on_render, on_commit);
        fixture.menus.replace(Some(StatusMenus {
            help,
            update,
            epoch: epoch.into(),
        }));
        rsx! { span { "{presentation.shown:?}" } }
    }

    /// Render a new contribution without draining its after-commit continuation.
    /// Keeping this boundary explicit distinguishes capture from close delivery.
    fn render_status(dom: &mut VirtualDom, fixture: &StatusFixture, value: InlinePresentation) {
        fixture.presentation.set(value);
        dom.mark_dirty(dioxus::core::ScopeId::APP);
        let mutations = dom.render_immediate_to_vec();
        assert!(
            !mutations.edits.is_empty(),
            "the visible status must change at this boundary"
        );
    }

    /// A status change closes the captured Update opening after commit, retains
    /// Help, and cannot replay against a fresh opening. Two committed changes
    /// before an effect drain must not erase the first movement by returning to A.
    #[farhelm_testtrace::test]
    fn status_movement_delivers_only_to_the_captured_update_opening() {
        let empty = InlinePresentation::default();
        let failed = InlinePresentation {
            shown: Some(crate::app_updater::InlineStatus::Failed),
            separate_progress_spinner: false,
        };
        for scenario in [
            "same opening",
            "fresh reopen",
            "return to original",
            "unchanged",
        ] {
            let fixture = StatusFixture::default();
            let mut dom = VirtualDom::new_with_props(status_fixture, fixture.clone());
            dom.rebuild_in_place();
            let StatusMenus {
                help,
                update,
                epoch,
            } = fixture.menus.borrow().expect("menu hooks rendered");
            dom.in_scope(dioxus::core::ScopeId::APP, || {
                help.begin_open(MenuOpenIntent::First, epoch);
                update.begin_open(MenuOpenIntent::First, epoch);
            });
            // The first effect still has not run when these menus open. It
            // seeds no movement and must not invalidate either fresh opening.
            dom.process_events();
            assert!(*help.open.peek(), "Help opened before the initial effect");
            assert!(*update.open.peek(), "initial status is a no-op");
            let opening = *update.open_generation.peek();

            if scenario == "unchanged" {
                dom.mark_dirty(dioxus::core::ScopeId::APP);
                dom.render_immediate(&mut dioxus::core::NoOpMutations);
            } else {
                render_status(&mut dom, &fixture, failed);
                assert!(*update.open.peek(), "capture must not close during render");
                if scenario == "fresh reopen" {
                    dom.in_scope(dioxus::core::ScopeId::APP, || {
                        update.close_menu.call(());
                        update.begin_open(MenuOpenIntent::First, epoch);
                    });
                    assert!(*update.open_generation.peek() > opening);
                } else if scenario == "return to original" {
                    render_status(&mut dom, &fixture, empty);
                    assert!(*update.open.peek(), "both renders precede delivery");
                }
            }
            dom.process_events();
            assert_eq!(
                *update.open.peek(),
                matches!(scenario, "fresh reopen" | "unchanged"),
                "{scenario}",
            );
            assert!(
                *help.open.peek(),
                "status movement must never select Help: {scenario}"
            );
        }
    }

    /// `None` is both the pre-reply state and the healthy steady state after
    /// agreeing replies; either way the client build is the exact answer, so
    /// there must be no loading placeholder and no wait for the network.
    #[farhelm_testtrace::test]
    fn no_skew_shows_the_client_build() {
        assert_eq!(displayed_version(None), skew::CLIENT_BUILD);
    }

    /// A silent helm is already represented by the skew system; the app bar
    /// keeps the client build visible because there is no remote stamp to show.
    #[farhelm_testtrace::test]
    fn silent_skew_shows_the_client_build() {
        assert_eq!(displayed_version(Some(&Skew::Silent)), skew::CLIENT_BUILD);
    }

    /// Once the helm reports a different build, the readout must expose that
    /// exact stamp so the user can identify the remote process behind the skew.
    #[farhelm_testtrace::test]
    fn reported_skew_shows_the_helm_build() {
        let skew = Skew::Reported("0.9.0-rc.1".to_string());
        assert_eq!(displayed_version(Some(&skew)), "0.9.0-rc.1");
    }

    /// Spec (Feedback): the `?` menu lists send feedback, documentation and
    /// release notes, SSH help and welcome in that order. Only a desktop app whose updater
    /// runs adds check for updates as the sixth item. The browser suite
    /// never has an updater, so this is the one place the desktop order is
    /// pinned.
    #[farhelm_testtrace::test]
    fn the_help_menu_lists_release_notes_before_the_update_check() {
        let common = [
            BarMenuItem::SendFeedback,
            BarMenuItem::Documentation,
            BarMenuItem::ReleaseNotes,
            BarMenuItem::SshHelp,
            BarMenuItem::Welcome,
        ];
        assert_eq!(help_menu_items(false), common);
        assert_eq!(
            help_menu_items(true),
            [&common[..], &[BarMenuItem::CheckForUpdates]].concat()
        );
    }
}

#!/usr/bin/env python3
"""Exercise the pinned cargo-about installer's own decisions with offline archives.

The download, cache, publication and nested-archive rules it shares with the other pinned tools are covered by
`test-install-pinned-nextest.py` and `test-install-pinned-cargo-deny.py` through `pinned_tool.py`. These tests cover
what is cargo-about's: the platform mapping, the pins file, the release URL, and that the executable is taken from the
directory the release archive wraps it in. Fixtures inject downloads and platform identity and never execute a
downloaded binary.
"""

import importlib.util
import io
import json
from pathlib import Path
import sys
import tarfile
import tempfile
import unittest


_path = Path(__file__).with_name("install-pinned-cargo-about.py")
_spec = importlib.util.spec_from_file_location("pinned_cargo_about", _path)
installer = importlib.util.module_from_spec(_spec)
exec(compile(_path.read_bytes(), str(_path), "exec"), installer.__dict__)
pinned_tool = sys.modules["pinned_tool"]

STEM = "cargo-about-0.9.3-x86_64-unknown-linux-musl"


def release_archive(binary):
    """Build an archive shaped like a cargo-about release asset: a directory holding the executable, README and licenses."""
    output = io.BytesIO()
    with tarfile.open(fileobj=output, mode="w:gz") as bundle:
        directory = tarfile.TarInfo(STEM)
        directory.type = tarfile.DIRTYPE
        bundle.addfile(directory)
        for name, data in (("cargo-about", binary), ("LICENSE-MIT", b"mit"), ("LICENSE-APACHE", b"apache"),
                           ("README.md", b"readme")):
            info = tarfile.TarInfo(f"{STEM}/{name}")
            info.size = len(data)
            info.mode = 0o755 if name == "cargo-about" else 0o644
            bundle.addfile(info, io.BytesIO(data))
    return output.getvalue()


class CargoAboutInstallerTests(unittest.TestCase):
    """Keep the dependency notices generated by exactly the pinned upstream cargo-about binary."""

    def test_platform_selection(self):
        """Linux hosts of either architecture and Apple Silicon map to pins; hosts nothing checks on refuse."""
        self.assertEqual(installer.target_for("Darwin", "arm64"), "aarch64-apple-darwin")
        self.assertEqual(installer.target_for("Linux", "x86_64"), "x86_64-unknown-linux-musl")
        self.assertEqual(installer.target_for("Linux", "arm64"), "aarch64-unknown-linux-musl")
        for system, machine in (("Darwin", "x86_64"), ("Windows", "AMD64")):
            with self.subTest(system=system, machine=machine), self.assertRaises(ValueError):
                installer.target_for(system, machine)

    def test_pins_cover_every_target(self):
        """The checked-in pins name every target `target_for` can return, with both digests for each."""
        pins = json.loads((installer.REPO / ".github/cargo-about-pins.json").read_text())
        supported = {("Darwin", "arm64"), ("Linux", "x86_64"), ("Linux", "arm64"), ("Linux", "aarch64")}
        self.assertEqual(set(pins["targets"]), {installer.target_for(system, machine) for system, machine in supported})
        for target, digests in pins["targets"].items():
            with self.subTest(target=target):
                self.assertEqual(set(digests), {"archive_sha256", "binary_sha256"})

    def test_install_publishes_the_nested_executable_from_the_release_url(self):
        """The URL names the version and target, and only the executable lands in the pin directory."""
        binary = b"fixture cargo-about"
        archive = release_archive(binary)
        pins = {"archive_sha256": pinned_tool.digest(archive), "binary_sha256": pinned_tool.digest(binary)}
        urls = []

        def fetch(url, path):
            urls.append(url)
            path.write_bytes(archive)

        with tempfile.TemporaryDirectory() as temporary:
            directory = installer.install(Path(temporary), "0.9.3", "x86_64-unknown-linux-musl", pins, fetch)
            self.assertEqual(directory.name, "0.9.3-x86_64-unknown-linux-musl")
            self.assertEqual([path.name for path in directory.iterdir()], ["cargo-about"])
            self.assertEqual((directory / "cargo-about").read_bytes(), binary)
            self.assertEqual(
                urls, [f"https://github.com/EmbarkStudios/cargo-about/releases/download/0.9.3/{STEM}.tar.gz"],
            )


if __name__ == "__main__":
    unittest.main()
